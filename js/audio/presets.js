// ---------- Variaciones ("🎲 Variar") ----------
const RANGES = {
  detune: [0, 1], spread: [0, 1], mix2: [0, 1], sub: [0, 1], noise: [0, 0.5], fm: [0, 1], cutoff: [0.05, 1], reso: [0, 0.85],
  envAmt: [0, 1], fa: [0.001, 3], fd: [0.02, 3], fs: [0, 1], a: [0.001, 2], d: [0.05, 3], s: [0, 1], r: [0.03, 4],
  vib: [0, 0.5], chorus: [0, 1], drive: [0, 0.8], rev: [0, 0.9], dly: [0, 0.6], lfoAmt: [0, 1],
};
const WAVES = ['sawtooth', 'square', 'triangle', 'sine'];
const RATIOS = [0.5, 1, 1.41, 2, 2.76, 3, 3.5, 4, 5, 7];
const DIVS = ['1/2', '1/4', '1/4T', '1/8', '1/8T', '1/16'];

// Mueve los parámetros alrededor del sonido actual sin perder su carácter
export function mutate(params, amount = 0.25) {
  const p = { ...params };
  const r = () => (Math.random() * 2 - 1) * amount;
  for (const [k, [lo, hi]] of Object.entries(RANGES)) {
    if (p[k] == null) continue;
    const span = hi - lo;
    // Los parámetros en cero se quedan en cero casi siempre (si no, todo termina sonando igual)
    if (p[k] === 0 && Math.random() > amount * 0.6) continue;
    p[k] = Math.min(hi, Math.max(lo, p[k] + r() * span * (k === 'a' || k === 'r' || k === 'd' ? 0.5 : 1)));
  }
  if (Math.random() < amount * 0.6) p.wave = WAVES[Math.floor(Math.random() * WAVES.length)];
  if (Math.random() < amount * 0.6) p.wave2 = WAVES[Math.floor(Math.random() * WAVES.length)];
  if (p.fm > 0 && Math.random() < amount) p.fmRatio = RATIOS[Math.floor(Math.random() * RATIOS.length)];
  if (p.unison > 1 || Math.random() < amount * 0.4) p.unison = Math.max(1, Math.min(7, Math.round(p.unison + r() * 4)));
  if (p.lfoAmt > 0 && Math.random() < amount) p.lfoDiv = DIVS[Math.floor(Math.random() * DIVS.length)];
  return p;
}
